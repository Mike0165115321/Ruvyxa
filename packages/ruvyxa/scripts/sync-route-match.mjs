/**
 * Keep `runtime/route-match.mjs` identical to `@ruvyxa/core`'s compiled matcher.
 *
 * `serverless-handler.mjs` is copied into a deployed function directory where no
 * bare specifier resolves, so it cannot `import '@ruvyxa/core/route-match'`
 * directly. A copy next to it keeps the deployment self-contained without
 * letting the handler grow a second port of the matching rules.
 *
 * The copy is committed rather than generated at build time, for two reasons
 * that were both real failures:
 *
 *   - `adapter-runner.mjs` imports the handler, and the Rust test suite executes
 *     the adapter runner. CI runs `cargo test` before `pnpm -r build`, so a
 *     generated-only file does not exist yet and the tests fail on a missing
 *     module.
 *   - The file is listed in the package's `files`. Publishing without a build
 *     step having run would ship a tarball whose handler throws on its first
 *     request.
 *
 * Being committed, it can drift from its source. `--check` is what stops that:
 * `ruvyxa`'s build runs it, so editing `@ruvyxa/core/src/route-match.ts` without
 * regenerating fails the build with the command to fix it, rather than shipping
 * two matchers that disagree — the exact defect this whole arrangement exists to
 * prevent.
 *
 * Usage:
 *   node scripts/sync-route-match.mjs           regenerate the copy
 *   node scripts/sync-route-match.mjs --check   fail if the copy is stale
 */

import { createRequire } from 'node:module'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const destination = path.join(packageRoot, 'runtime', 'route-match.mjs')
const checkOnly = process.argv.includes('--check')

const BANNER = `// GENERATED by scripts/sync-route-match.mjs from @ruvyxa/core/route-match.
// Do not edit: edit packages/@ruvyxa/core/src/route-match.ts instead, then run
// \`pnpm --filter ruvyxa sync:route-match\`.
`

function resolveCompiledMatcher() {
  try {
    return require.resolve('@ruvyxa/core/route-match')
  } catch (error) {
    throw new Error(
      'Cannot resolve @ruvyxa/core/route-match. Build @ruvyxa/core first ' +
        '(`pnpm --filter @ruvyxa/core build`), then re-run this script.',
      { cause: error },
    )
  }
}

const source = resolveCompiledMatcher()
const compiled = readFileSync(source, 'utf8')

// A bare specifier or a Node builtin in the copied output would fail only at
// request time in a deployed function, so it is rejected here instead.
const foreignImport = /^\s*(?:import|export)\b[^'"]*from\s+['"]([^'".][^'"]*)['"]/m.exec(compiled)
if (foreignImport) {
  throw new Error(
    `@ruvyxa/core/route-match must stay dependency-free; it imports "${foreignImport[1]}". ` +
      'A serverless function bundle resolves no bare specifiers.',
  )
}

const expected = `${BANNER}${compiled}`

if (checkOnly) {
  let actual = null
  try {
    actual = readFileSync(destination, 'utf8')
  } catch {
    // Falls through to the same failure as a stale file.
  }
  if (actual !== expected) {
    const reason = actual === null ? 'is missing' : 'is out of date'
    console.error(
      `runtime/route-match.mjs ${reason}.\n\n` +
        'It is the copy of @ruvyxa/core/route-match that ships inside serverless\n' +
        'function bundles. Letting it drift means the browser router and the\n' +
        'deployed handler can resolve the same URL to different routes.\n\n' +
        'Regenerate and commit it:\n\n' +
        '  pnpm --filter ruvyxa sync:route-match\n',
    )
    process.exit(1)
  }
  console.log('route-match.mjs is in sync with @ruvyxa/core/route-match')
} else {
  mkdirSync(path.dirname(destination), { recursive: true })
  writeFileSync(destination, expected, 'utf8')
  console.log(`route-match.mjs synced from ${path.relative(packageRoot, source)}`)
}
